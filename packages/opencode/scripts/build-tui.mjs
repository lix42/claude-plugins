import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { transformAsync } from '@babel/core'
import typescript from '@babel/preset-typescript'
import solid from 'babel-preset-solid'

const source = new URL('../src/tui.tsx', import.meta.url)
const directory = new URL('../dist/', import.meta.url)
const result = await transformAsync(await readFile(source, 'utf8'), {
  filename: fileURLToPath(source),
  configFile: false,
  babelrc: false,
  presets: [[solid, { moduleName: '@opentui/solid', generate: 'universal' }], [typescript]],
  plugins: [() => ({ visitor: {
    ImportDeclaration(path) {
      // The generated file lives beside src/, not inside it. Keep shared source
      // modules external so OpenCode's host supplies its own runtime instances.
      const value = path.node.source.value
      if (value.startsWith('./')) path.node.source.value = `../src/${value.slice(2)}`
    },
  } })],
})
if (!result?.code) throw new Error('Solid compilation produced no TUI code')
const banner = '// Generated by npm run build:tui from ../src/tui.tsx. Do not edit.\n'
const outputs = {
  'tui.js': `${banner}${result.code}\n`,
  'tui.d.ts': `${banner}import type { Plugin } from '@opencode/plugin/tui'\ndeclare const plugin: Plugin.Definition\nexport default plugin\n`,
}
await mkdir(directory, { recursive: true })
for (const [name, expected] of Object.entries(outputs)) {
  const file = new URL(name, directory)
  if (process.argv.includes('--check')) {
    const actual = await readFile(file, 'utf8').catch(() => '')
    if (actual !== expected) throw new Error(`${name} is missing or stale; run npm run build:tui and commit packages/opencode/dist`)
  } else {
    await writeFile(file, expected)
  }
}
