import { rollup, unsettledDeps } from './graph.ts'
import type { Index } from './graph.ts'
import { cmp, compareTasks, STATUS_BOX, taskPath } from './model.ts'
import type { Epic, Plan, Task } from './model.ts'

export const GENERATED_MARK = '<!-- Generated by the tasks CLI. Edit tasks/ and run `tasks render`; never edit this file. -->'

/** Epics in display order, each with its tasks sorted. Flat mode yields one unnamed group. */
export function groups(plan: Plan): { epic: Epic | null; tasks: Task[] }[] {
  if (plan.mode === 'flat') return [{ epic: null, tasks: [...plan.tasks].sort(compareTasks) }]
  const epics = [...plan.epics].sort((a, b) => a.order - b.order || cmp(a.name, b.name))
  return epics.map(epic => ({
    epic,
    tasks: plan.tasks.filter(t => t.epic === epic.name).sort(compareTasks),
  }))
}

export function renderIndex(plan: Plan, idx: Index): string {
  const out: string[] = [GENERATED_MARK, '']
  const header = plan.header.trim()
  if (header !== '') out.push(header, '')
  out.push('## Dependencies', '')
  out.push(...(plan.mode === 'epic' ? renderRollup(plan, idx) : renderTaskGraph(plan, idx)))
  out.push('## Tasks', '')
  out.push(
    '**Legend:** `[ ]` todo · `[~]` doing · `[x]` done · `[-]` closed. ' +
      'Each task file\'s frontmatter is the source of truth; query with `tasks ready`, `tasks show <id>`.',
  )
  out.push('')
  for (const { epic, tasks } of groups(plan)) {
    if (epic !== null) {
      out.push(`### ${epic.name} — [progress](progress/${epic.name}.md)`)
      if (epic.title !== epic.name) out.push(`**${epic.title}**`)
      if (epic.blurb !== '') out.push(...epic.blurb.split('\n').map(l => (l === '' ? '>' : `> ${l}`)))
      out.push('')
    }
    if (tasks.length === 0) {
      out.push('_No tasks._', '')
      continue
    }
    for (const t of tasks) out.push(renderItem(t, idx))
    out.push('')
  }
  return out.join('\n').replace(/\n+$/, '\n')
}

function renderItem(t: Task, idx: Index): string {
  const parts: string[] = []
  if (t.status === 'closed' && t.closedInto !== '') parts.push(`closed into \`${t.closedInto}\``)
  if (t.summary !== '') parts.push(t.summary)
  const waits = t.status === 'todo' || t.status === 'doing' ? unsettledDeps(t, idx) : []
  if (waits.length > 0) parts.push(`**waits on** ${waits.map(d => `\`${d}\``).join(', ')}`)
  if (t.priority === 'low') parts.push('**low priority**')
  if (t.priority === 'blocked') parts.push('**blocked**')
  const tail = parts.length > 0 ? ` — ${parts.join(' · ')}` : ''
  return `- [${STATUS_BOX[t.status]}] [${escapeLinkText(t.title)}](${taskPath(t.id)})${tail}`
}

/** Escape brackets outside code spans; inside them a backslash would show. */
function escapeLinkText(s: string): string {
  return s
    .split(/(`[^`]*`)/)
    .map(part => (part.startsWith('`') ? part : part.replace(/([[\]])/g, '\\$1')))
    .join('')
}

function renderRollup(plan: Plan, idx: Index): string[] {
  const names = groups(plan).map(g => g.epic!.name)
  const edges = rollup(plan, idx)
  return [
    'Epic rollup, derived from the open tasks\' dependencies (a cycle here is not a defect):',
    '',
    '```mermaid',
    'graph TD',
    ...names.map(n => `  ${n}`),
    ...edges.map(([a, b]) => `  ${a} --> ${b}`),
    '```',
    '',
  ]
}

function renderTaskGraph(plan: Plan, idx: Index): string[] {
  const live = plan.tasks.filter(t => t.status !== 'closed').sort((a, b) => cmp(a.id, b.id))
  if (live.length === 0) return ['_No tasks._', '']
  const edges: string[] = []
  for (const t of live)
    for (const d of [...t.deps].sort(cmp)) if (idx.get(d)?.status !== 'closed') edges.push(`  ${d} --> ${t.id}`)
  return ['```mermaid', 'graph TD', ...live.map(t => `  ${t.id}`), ...edges, '```', '']
}
